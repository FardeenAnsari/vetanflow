import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const handoffPath = join(root, 'docs', 'HANDOFF.md')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

function run(command) {
  try {
    return execSync(command, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
  } catch {
    return ''
  }
}

const branch = run('git branch --show-current') || 'main'
const status = run('git status --short')
const scripts = Object.keys(pkg.scripts ?? {}).sort()

const snapshot = [
  '<!-- HANDOFF:AUTOGENERATED_START -->',
  '## Generated Snapshot',
  '',
  `- Updated: ${new Date().toISOString()}`,
  `- Branch: ${branch}`,
  `- Working tree: ${status ? 'has uncommitted changes' : 'clean'}`,
  `- Node scripts: ${scripts.map((script) => `\`${script}\``).join(', ')}`,
  '- Verification command: `npm run verify`',
  '- Frontend dev URL: `http://127.0.0.1:5173/`',
  '- Backend health URL: `http://localhost:4000/health`',
  '',
  '<!-- HANDOFF:AUTOGENERATED_END -->',
].join('\n')

const existing = readFileSync(handoffPath, 'utf8')
const pattern = /<!-- HANDOFF:AUTOGENERATED_START -->[\s\S]*<!-- HANDOFF:AUTOGENERATED_END -->/

if (!pattern.test(existing)) {
  throw new Error('HANDOFF.md is missing autogenerated markers')
}

writeFileSync(handoffPath, `${existing.replace(pattern, snapshot).trim()}\n`)
